interface I18nState {
  locale: Locale;
  setLocale: (locale: Locale) => void;
}

export const useI18nStore = create<I18nState>((set) => ({
  locale: "zh-CN",
  setLocale: (locale) => {
    document.documentElement.lang = locale;
    set({ locale });
  },
}));

export function detectBrowserLocale(): Locale {
  const lang = navigator.language;
  if (lang === "zh-TW" || lang === "zh-Hant" || lang.startsWith("zh-Hant"))
    return "zh-TW";
  if (lang.startsWith("zh")) return "zh-CN";
  if (lang.startsWith("ja")) return "ja-JP";
  if (lang.startsWith("ko")) return "ko-KR";
  return "en-US";
}

export function initLocaleFromConfig(configLocale: string) {
  const l = configLocale as Locale;
  if (VALID_LOCALES.includes(l)) {
    useI18nStore.getState().setLocale(l);
  } else {
    useI18nStore.getState().setLocale(detectBrowserLocale());
  }
}

export function t(key: string): string {
  const locale = useI18nStore.getState().locale;
  return messages[locale]?.[key] ?? key;
}

export function tWith(key: string, vars: Record<string, string>): string {
  let result = t(key);
  for (const [k, v] of Object.entries(vars)) {
    result = result.replace(`{${k}}`, v);
  }
  return result;
}

export function useT() {
  const locale = useI18nStore((s) => s.locale);
  return (key: string) => messages[locale]?.[key] ?? key;
}

export { VALID_LOCALES };
